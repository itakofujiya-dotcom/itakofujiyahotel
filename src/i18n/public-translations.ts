const sortedPublicPhrases = [...publicPhrases].sort(
  ([left], [right]) => right.length - left.length,
)

export function translateSiteText(value: string, locale: SiteLocale): string {
  if (locale === 'ja') return value
  let translated = value
  for (const [ja, ko] of sortedPublicPhrases)
    translated = translated.split(ja).join(ko)
  return translateAdminText(translated, 'ko').replace(
    /(\d{1,2}:\d{2})から/g,
    '$1부터',
  )
}
